/** Version stamp shown on both documents. Bump when the text changes. */
const LAST_UPDATED = '١٢ فبراير ٢٠٢٦'
const CONTACT_EMAIL = 'legal@mawzun.org'

type Block =
  | { kind: 'p'; text: string }
  | { kind: 'list'; items: string[] }
  | { kind: 'callout'; items: string[] }

type Clause = { heading: string; blocks: Block[] }

function ClauseSection({ heading, blocks, index }: Clause & { index: number }) {
  return (
    <section className="legal-clause" id={`clause-${index}`}>
      <h2>
        <span className="legal-clause-num" aria-hidden="true">
          {index}
        </span>
        <span className="legal-clause-text">{stripNumber(heading)}</span>
      </h2>
      {blocks.map((b, i) => {
        if (b.kind === 'p') return <p key={i}>{b.text}</p>
        if (b.kind === 'list')
          return (
            <ul key={i} className="legal-list">
              {b.items.map((it, j) => (
                <li key={j}>{it}</li>
              ))}
            </ul>
          )
        return (
          <div key={i} className="legal-callout">
            {b.items.map((it, j) => (
              <p key={j}>{it}</p>
            ))}
          </div>
        )
      })}
    </section>
  )
}

/** Headings carry a hand-written Arabic numeral ("٣. نطاق …"); the layout
 *  supplies its own numbering, so drop the prefix to avoid showing it twice. */
function stripNumber(heading: string): string {
  return heading.replace(/^[\u0660-\u0669\u06F0-\u06F9\d]+\s*[.·\-–—]\s*/, '')
}


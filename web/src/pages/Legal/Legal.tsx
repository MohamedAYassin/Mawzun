function LegalDocument({
  title,
  summary,
  clauses,
  navigate,
}: {
  title: string
  summary: string
  clauses: Clause[]
  navigate: (path: string) => void
}) {
  return (
    <Shell navigate={navigate}>
      <div className="landing-shell legal-wrap">
        <article className="legal-doc">
          <header className="legal-head">
            <p className="legal-eyebrow">وثيقة قانونية</p>
            <h1>{title}</h1>
            <p className="legal-summary">{summary}</p>
            <p className="legal-updated">
              آخر تحديث: <time dateTime="2026-02-12">{LAST_UPDATED}</time>
            </p>
          </header>

          <nav className="legal-toc" aria-labelledby="legal-toc-title">
            <h2 id="legal-toc-title" className="legal-toc-title">
              فهرس البنود
            </h2>
            <ol className="legal-toc-list">
              {clauses.map((c, i) => (
                <li key={c.heading}>
                  <a href={`#clause-${i + 1}`}>{stripNumber(c.heading)}</a>
                </li>
              ))}
            </ol>
          </nav>

          <div className="legal-clauses">
            {clauses.map((c, i) => (
              <ClauseSection key={c.heading} index={i + 1} {...c} />
            ))}
          </div>
        </article>
      </div>
    </Shell>
  )
}

